/**
 * A booth line from one heat, never the same one twice running.
 * Unknown heats fall back to naughty. An empty pool returns null.
 */
export function pickBooth(pool = 'turn', last = null, heat = 'naughty') {
  const book = BOOTH[heat] ?? BOOTH.naughty;
  const lines = book[pool] ?? book.turn;
  if (!lines || lines.length === 0) return null;
  const options = lines.length > 1 ? lines.filter((line) => line !== last) : lines;
  return options[Math.floor(Math.random() * options.length)];
}
